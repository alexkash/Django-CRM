"""Money in words must agree with the printed Ukrainian invoice total."""

from decimal import Decimal

import pytest


@pytest.mark.parametrize(
    ("amount", "expected"),
    [
        ("0", "Нуль гривень 00 копійок"),
        ("1.01", "Одна гривня 01 копійка"),
        ("2.02", "Дві гривні 02 копійки"),
        ("5.05", "П’ять гривень 05 копійок"),
        ("11.11", "Одинадцять гривень 11 копійок"),
        ("21.21", "Двадцять одна гривня 21 копійка"),
        ("1001.14", "Одна тисяча одна гривня 14 копійок"),
        ("1011", "Одна тисяча одинадцять гривень 00 копійок"),
        ("22000", "Двадцять дві тисячі гривень 00 копійок"),
        ("1000000", "Один мільйон гривень 00 копійок"),
        ("2000000000", "Два мільярди гривень 00 копійок"),
        (
            "9999999999.99",
            "Дев’ять мільярдів дев’ятсот дев’яносто дев’ять мільйонів дев’ятсот дев’яносто дев’ять тисяч дев’ятсот дев’яносто дев’ять гривень 99 копійок",
        ),
    ],
)
def test_amount_in_words(amount, expected):
    from invoices.formatting import amount_in_words_uk

    assert amount_in_words_uk(Decimal(amount)) == expected
